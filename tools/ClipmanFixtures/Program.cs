        // RichTextDatabase exists so other clients can prove they preserve
        // fields they do not themselves understand. The CLI and Linux backend
        // have no RichText field and must round-trip it untouched.
        private static ClipDatabase RichTextDatabase()
        {
            var database = EmptyDatabase();

            var rich = NewEntry("20000000000000000000000000000001", "styled text");
            rich.Name = "rich";
            rich.RichText = new RichTextPayload();
            rich.RichText.Version = 1;
            rich.RichText.HtmlFragment = "<p><b>styled</b> text</p>";
            rich.RichText.RtfBase64 = Convert.ToBase64String(Encoding.ASCII.GetBytes(@"{\rtf1 styled text}"));
            rich.RichText.PreferredFormat = "html";
            rich.RichTextUpdatedUnixMs = BaseUnixMs;

            var plain = NewEntry("20000000000000000000000000000002", "ordinary text");
            plain.ManualOrder = 2;

            database.Entries.Add(rich);
            database.Entries.Add(plain);
            return database;
        }

        private static ClipDatabase TombstoneDatabase()
        {
            var database = EmptyDatabase();
            database.Entries.Add(NewEntry("30000000000000000000000000000001", "surviving entry"));

            var recent = new DeletedClipEntry();
            recent.Id = "30000000000000000000000000000002";
            recent.TextHash = "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855";
            recent.DeletedUnixMs = BaseUnixMs;
            recent.SourceMachine = "windows-fixture";

            // Just inside the documented 90-day retention window.
            var nearBoundary = new DeletedClipEntry();
            nearBoundary.Id = "30000000000000000000000000000003";
            nearBoundary.TextHash = "5891b5b522d5df086d0ff0b110fbd9d21bb4fc7163af34d08286a2e846f6be03";
            nearBoundary.DeletedUnixMs = BaseUnixMs - (89L * 24L * 60L * 60L * 1000L);
            nearBoundary.SourceMachine = "windows-fixture";

            // Deliberately blank source machine and text hash.
            var sparse = new DeletedClipEntry();
            sparse.Id = "30000000000000000000000000000004";
            sparse.TextHash = string.Empty;
            sparse.DeletedUnixMs = BaseUnixMs;
            sparse.SourceMachine = string.Empty;

            database.DeletedEntries.Add(recent);
            database.DeletedEntries.Add(nearBoundary);
            database.DeletedEntries.Add(sparse);
            return database;
        }

        // Verify reads blobs another client wrote and reports whether the
        // canonical Windows loader accepts them. It closes the loop the other
        // way round: fixtures prove Windows-to-others, this proves others-to-Windows.
        private static int Verify(string directory)
        {
            if (!Directory.Exists(directory))
            {
                Console.Error.WriteLine("no such directory: " + directory);
                return 2;
            }
            var failures = 0;
            var checkedCount = 0;
            var files = Directory.GetFiles(directory, "*.clipdb");
            Array.Sort(files, StringComparer.OrdinalIgnoreCase);
            foreach (var file in files)
            {
                var name = Path.GetFileNameWithoutExtension(file);
                var passwordFile = Path.Combine(directory, name + ".password");
                var password = File.Exists(passwordFile) ? File.ReadAllText(passwordFile, Encoding.UTF8) : string.Empty;
                checkedCount++;
                try
                {
                    var database = ClipDatabaseFile.Load(file, password);
                    Console.Out.WriteLine("ok    " + name + ": " + database.Entries.Count + " entries, " + database.DeletedEntries.Count + " tombstones");
                    var expected = Path.Combine(directory, name + ".expected.json");
                    if (File.Exists(expected))
                    {
                        var actual = DescribeDatabase(database);
                        if (!string.Equals(actual, File.ReadAllText(expected, Encoding.UTF8), StringComparison.Ordinal))
                        {
                            Console.Error.WriteLine("FAIL  " + name + ": contents differ from " + Path.GetFileName(expected));
                            failures++;
                        }
                    }
                }
                catch (Exception error)
                {
                    Console.Error.WriteLine("FAIL  " + name + ": " + error.Message);
                    failures++;
                }
            }
            Console.Out.WriteLine(checkedCount + " checked, " + failures + " failed");
            return failures == 0 ? 0 : 1;
        }

        private static string Number(long value)
        {
            return value.ToString(CultureInfo.InvariantCulture);
        }

        // Quote emits JSON with every non-ASCII and control character escaped,
        // so the fixture files stay reviewable as plain ASCII in a diff and are
        // not silently altered by an editor's encoding.
        private static string Quote(string value)
        {
            if (value == null) return "null";
            var text = new StringBuilder("\"");
            foreach (var character in value)
            {
                switch (character)
                {
                    case '"': text.Append("\\\""); break;
                    case '\\': text.Append("\\\\"); break;
                    case '\b': text.Append("\\b"); break;
                    case '\f': text.Append("\\f"); break;
                    case '\n': text.Append("\\n"); break;
                    case '\r': text.Append("\\r"); break;
                    case '\t': text.Append("\\t"); break;
                    default:
                        if (character < 0x20 || character > 0x7e)
                        {
                            text.Append("\\u").Append(((int)character).ToString("x4", CultureInfo.InvariantCulture));
                        }
                        else
                        {
                            text.Append(character);
                        }
                        break;
                }
            }
            return text.Append("\"").ToString();
        }
